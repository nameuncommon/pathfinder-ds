// The docs block for every component page: what it is for, when to use it and
// when not, do and don't, accessibility, the tokens it reads, and its Figma node.
// Kept in one file so the pages read the same and the copy is easy to review.

const figma = (node: string) => `https://www.figma.com/design/ZKIX0oa2fm0OwNIGvRWJXJ?node-id=${node.replace(':', '-')}`

interface Doc {
  what: string
  use: string
  avoid: string
  dos: Array<[string, string]>
  a11y: string
  tokens: string[]
  node: string
}

function render(d: Doc): string {
  return [
    d.what,
    '',
    `**Use it when** ${d.use} **Not when** ${d.avoid}`,
    '',
    '| Do | Don’t |',
    '|---|---|',
    ...d.dos.map(([y, n]) => `| ${y} | ${n} |`),
    '',
    `**Accessibility.** ${d.a11y}`,
    '',
    `**Tokens.** ${d.tokens.map((t) => `\`${t}\``).join(', ')}`,
    '',
    `[Open in Figma](${figma(d.node)})`,
  ].join('\n')
}

